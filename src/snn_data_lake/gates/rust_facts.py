# distinct-from: gradient_claim_gate.py -- its _rust_triples PARSES literal values out of one declaration grammar; this STRIPS literals from token text before spelling scans (consolidates eprop_transport_gate._RS_LITERAL)
#: Rust string / char literals, raw and byte forms included. A spelling INSIDE one is text, not code:
#: every gate that scans token text for a method/call spelling strips these first (shared, P2; moved
#: here from eprop_transport_gate when gradient_claim_gate needed the same fix, Codex r3 F-4).
RUST_LITERAL = re.compile(r"""b?r(#*)".*?"\1|b?"(?:\\.|[^"\\])*"|b?'(?:\\[^']+|[^\\'])'""", re.S)


def strip_literals(text: str | None) -> str:
    """`text` with every Rust string/char literal replaced by `""`."""
    return RUST_LITERAL.sub('""', text or "")


class RustFactsUnavailable(RuntimeError):
    """The Rust half of a gate could not run. A gate must report this as a RED, never skip it."""


def rust_files(root: Path = ROOT, sub: str = NATIVE_DIR) -> list[Path]:
    """Tracked and untracked-but-not-ignored `.rs` files under `sub` (git's view, like p4c_ratchet)."""
    base = Path(root)
    if not (base / sub).exists():
        return []
    try:
        out = subprocess.run(
            ["git", "-C", str(base), "ls-files", "-co", "--exclude-standard", "--", f"{sub}/*.rs"],
            capture_output=True,
            text=True,
            check=True,
        ).stdout
    except (OSError, subprocess.CalledProcessError) as exc:
        raise RustFactsUnavailable(f"git ls-files failed under {base / sub}: {exc}") from exc
    seen = sorted(base / p for p in out.splitlines() if p.strip())
    # Fail CLOSED on Rust git does not show (gitignored): "native/ ABSENT" must never print while .rs
    # exists on disk (panel A, 2026-10-17). Cargo build output (`target/`) is the only allowed exclusion.
    disk = {
        p for p in (base / sub).rglob("*.rs") if "target" not in p.relative_to(base / sub).parts
    }
    hidden = sorted(disk - set(seen))
    if hidden:
        raise RustFactsUnavailable(
            f"{len(hidden)} .rs file(s) under {sub}/ are invisible to git (ignored?): {hidden[:3]}"
        )
    return seen


def binary(root: Path = ROOT) -> Path:
    """Build (cargo no-ops when current) and return the rsfacts executable."""
    cargo = shutil.which("cargo")
    manifest = Path(root) / RSFACTS / "Cargo.toml"
    if cargo is None:
        raise RustFactsUnavailable("cargo not on PATH: the Rust half of this gate cannot run")
    if not manifest.exists():
        raise RustFactsUnavailable(f"missing {manifest}")
    target = Path(root) / RSFACTS / "target"
    env = dict(os.environ, CARGO_TARGET_DIR=str(target))
    r = subprocess.run(
        [cargo, "build", "--release", "--locked", "--quiet", "--manifest-path", str(manifest)],
        capture_output=True,
        text=True,
        env=env,
    )
    if r.returncode != 0:
        raise RustFactsUnavailable(f"rsfacts build failed:\n{r.stderr[-2000:]}")
    exe = target / "release" / ("rsfacts.exe" if os.name == "nt" else "rsfacts")
    if not exe.exists():
        raise RustFactsUnavailable(f"rsfacts built but {exe} is missing")
    return exe


def facts(paths, root: Path = ROOT, allow_errors: bool = False) -> list[dict]:
    """One fact dict per file. A parse failure raises unless `allow_errors` (self-checks only)."""
    paths = [str(p) for p in paths]
    if not paths:
        return []
    r = subprocess.run(
        [str(binary(root)), "-"], input="\n".join(paths), capture_output=True, text=True
    )
    if r.returncode != 0:
        raise RustFactsUnavailable(f"rsfacts exited {r.returncode}: {r.stderr[-2000:]}")
    out = [json.loads(line) for line in r.stdout.splitlines() if line.strip()]
    if len(out) != len(paths):
        raise RustFactsUnavailable(f"rsfacts returned {len(out)} records for {len(paths)} files")
    bad = [f for f in out if not f.get("ok") or f.get("schema") != SCHEMA]
    if bad and not allow_errors:
        raise RustFactsUnavailable(
            "unparseable Rust: " + "; ".join(f"{b['file']}: {b.get('err')}" for b in bad)
        )
    flags = test_file_flags(out)
    for f in out:
        _mark_test_dir(f, flags[f["file"]])
    return out


_TEST_DIRS = ("tests", "benches", "examples")
_PATH_ATTR = re.compile(r'\bpath\s*=\s*"([^"]+)"')


# distinct-from: policy_manifest.py docs_only_battery.py eligible_circuit_census.py sleep_plasticity_ab.py language_readout_slda.py -- heads, doc readers, census records, A/B arms, a readout split; this classifies RUST crate files as test code (native_dormancy's _in_test_dir copy is retired by the dorm fold-3 lane)
def crate_dirs(files) -> set[Path]:
    """Crate roots: every directory holding a Cargo.toml above a file, plus the parent of any
    src/lib.rs / src/main.rs (fixture trees may have no manifest)."""
    dirs = set()
    for p in map(Path, files):
        dirs |= {a for a in p.parents if (a / "Cargo.toml").is_file()}
        if p.name in ("lib.rs", "main.rs") and p.parent.name == "src":
            dirs.add(p.parent.parent)
    return dirs


MOD_RS = ("mod.rs", "lib.rs", "main.rs")  # files whose `mod x;` children sit beside them


# distinct-from: docs_only_battery.py atlas_node_gate.py -- a git-index hash and a node census; this names the FILES a Rust `mod x;` declaration can load (the ONE resolver: test_file_flags here and native_dormancy's mod tree)
def mod_files(
    declaring: PurePath, m: dict, mod_rs: bool, cfg_test: bool = False
) -> tuple[bool, list[PurePath]]:
    """(loaded through `#[path]`, candidate files -- not normalised) a non-inline `mod x;` in
    `declaring` can load, by Rust's rules: the base is the file's directory for a mod-rs file (one of
    `MOD_RS`, or any file itself loaded through `#[path]`), else `<stem>/`; inline module names are
    subdirectories; a `#[path = ".."]` outside an inline module is relative to the file's directory,
    inside one to that base; otherwise `x.rs` | `x/mod.rs`. cfg(test) declarations are skipped unless
    `cfg_test` (the dormancy mod tree keeps them)."""
    if m["inline"] or (m["cfg_test"] and not cfg_test):
        return False, []
    base = declaring.parent if mod_rs else declaring.with_suffix("")
    base = base.joinpath(*m["mod"].split("::")) if m["mod"] else base
    a = _attr(m["attrs"], "path")
    hit = _PATH_ATTR.search(a) if a else None
    if hit:
        return True, [(base if m["mod"] else declaring.parent) / hit.group(1)]
    return False, [base / f"{m['name']}.rs", base / m["name"] / "mod.rs"]


def test_file_flags(file_facts) -> dict[str, bool]:
    """{file: is test code}: the ONE classification every gate uses (P2, Codex r4 N-3). A file is test
    code iff its path relative to its DEEPEST crate root starts with tests/ benches/ examples/ and no
    PRODUCTION file reaches it through a `mod x;` declaration (`mod_files`): production is the
    FIXPOINT grown from the non-test files, so a test file's `#[path]` include promotes nothing
    (Codex r5 R-2) and a production include reaches the included file's own children (r5 N5-1)."""
    files = [Path(f["file"]) for f in file_facts]
    dirs = crate_dirs(files)
    by_path = {p.resolve(): f for f, p in zip(file_facts, files, strict=True)}
    prod = set()
    for p in files:
        crate = max((d for d in dirs if d in p.parents), key=lambda d: len(d.parts), default=None)
        rest = p.relative_to(crate).parts if crate else ()
        if not (rest and rest[0] in _TEST_DIRS):
            prod.add(p.resolve())
    todo, via_path = list(prod), set()
    while todo:
        p = todo.pop()
        f = by_path[p]
        for m in f.get("mods", []) if f.get("ok") else []:
            is_path, targets = mod_files(p, m, p.name in MOD_RS or p in via_path)
            for t in (t.resolve() for t in targets):
                if t in by_path and t not in prod:
                    prod.add(t)
                    todo.append(t)
                    if is_path:
                        via_path.add(t)
    return {f["file"]: p.resolve() not in prod for f, p in zip(file_facts, files, strict=True)}


def _mark_test_dir(f: dict, hit: bool) -> None:
    """A test-code file (see `test_file_flags`) gets cfg_test on every record and its paths moved to
    test_paths, so no gate re-derives the rule (Codex r3 F-5)."""
    f["test_file"] = hit
    if hit and f.get("ok"):
        f["test_paths"] = sorted({*f.get("test_paths", []), *f.get("paths", [])})
        f["paths"] = []
        for recs in f.values():
            if isinstance(recs, list):
                for r in recs:
                    if isinstance(r, dict) and "cfg_test" in r:
                        r["cfg_test"] = True


def facts_for_source(
    text: str, name: str = "fixture.rs", root: Path = ROOT, allow_errors=False
) -> dict:
    """Facts for one snippet, via a temp file: the constructed-red helper every gate self-check uses."""
    with tempfile.TemporaryDirectory() as d:
        p = Path(d) / name
        p.write_text(text, encoding="utf-8")
        return facts([p], root, allow_errors=allow_errors)[0]


def native_status(root: Path = ROOT) -> tuple[str, list[dict]]:
    """("ABSENT", []) when there is no Rust under native/, else ("N files", facts). Fails closed."""
    files = rust_files(root)
    if not files:
        return "native/ ABSENT (0 .rs files)", []
    return f"native/ PRESENT ({len(files)} .rs files)", facts(files, root)


# ---- the PyO3 export map ---------------------------------------------------------------------

_NAME_ARG = re.compile(r'\bname\s*=\s*"([^"]+)"')


# distinct-from: amdahl_gate.py unit_label_gate.py eprop_transport_gate.py attention_schema.py rule_composer.py recursive_tom.py fear_conditioning.py proximity_replay.py -- those read Python AST nodes, objects or VSA content; these read the Rust ATTRIBUTE TEXT rsfacts prints
_WRAP = re.compile(r"\bwrap_pyfunction\s*!\s*\(\s*([\w:]+)")
_IDENT = re.compile(r"[A-Za-z_]\w*")
# One layer an initializer may wrap an identifier in and still name the SAME value (re-panel A RA-5/RA-6):
# a trailing `?`, `.clone()` or `.into()`, then `&` / `&mut`, then parentheses -- suffix first, so
# `(g).clone()` peels to `(g)`, not to `g).clone(`.
_ALIAS_SKIN = re.compile(
    r"(.*?)\s*(?:\?|\.\s*(?:clone|into)\s*\(\s*\))|&\s*(?:mut\s+)?(.*)|\(\s*(.*?)\s*\)"
)


def alias_root(init: str) -> str | None:
    """The identifier `init` aliases once every `_ALIAS_SKIN` layer is peeled (`(&g)?` -> `g`), else
    None: any other expression (a call, a literal, another method) is a NEW value."""
    s = init.strip()
    while m := _ALIAS_SKIN.fullmatch(s):
        s = m.group(m.lastindex)
    m = _IDENT.fullmatch(s)
    return m.group(0) if m else None


def _attr_name(a: str) -> str:
    """Last path segment of a Rust attribute text: `pyo3::pymodule(gil_used = false)` -> `pymodule`."""
    return re.split(r"[(= ]", a, maxsplit=1)[0].split("::")[-1]


def _attr(attrs, head):
    """The first Rust attribute whose LAST path segment is `head` (`pyclass` == `pyo3::pyclass`)."""
    return next((a for a in attrs if _attr_name(a) == head), None)


def _top_args(a: str) -> list[str]:
    """Top-level comma-separated arguments of `head(...)`: `pyo3(signature = (x, name = "d"), name = "n")`
    -> ['signature = (x, name = "d")', 'name = "n"']. Nested parens/brackets and strings are skipped."""
    inner = a[a.find("(") + 1 : a.rfind(")")] if "(" in a else ""
    out, depth, cur, quote = [], 0, "", False
    for ch in inner:
        if ch == '"':
            quote = not quote
        elif not quote and ch in "([{":
            depth += 1
        elif not quote and ch in ")]}":
            depth -= 1
        if ch == "," and depth == 0 and not quote:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    return [*out, cur.strip()] if cur.strip() else out


def _renamed(attrs, default):
    """The Python name a TOP-LEVEL `name = "..."` argument gives (panel A: `signature = (x, name = "d")`
    is a default argument value, not a rename)."""
    for a in attrs:
        if _attr_name(a) in ("pyo3", "pyclass", "pyfunction"):
            for arg in _top_args(a):
                m = _NAME_ARG.fullmatch(arg)
                if m:
                    return m.group(1)
    return default


def _method_key(fn):
    """(Python-visible member name, kind) of a #[pymethods] fn: `#[new]` is the constructor, getters and
    setters expose a property (`#[getter(x)]`, else the fn name minus `get_`/`set_`, PyO3's rule)."""
    if _attr(fn["attrs"], "new"):
        return "__new__", "constructor"
    for kind, prefix in (("getter", "get_"), ("setter", "set_")):
        a = _attr(fn["attrs"], kind)
        if a:
            m = re.search(r"\(\s*\"?(\w+)\"?\s*\)", a)
            name = m.group(1) if m else fn["name"].removeprefix(prefix)
            return name, kind
    return _renamed(fn["attrs"], fn["name"]), "method"


def pyo3_exports(file_facts) -> dict[str, dict]:
    """Python-visible name -> {"rust": item name, "file", "line", "kind"}; class methods as "Cls.meth"."""
    out: dict[str, dict] = {}
    pyfns: dict[str, dict] = {}
    pyclasses: dict[str, tuple[str, dict]] = {}
    for f in file_facts:
        for fn in f.get("fns", []):
            if _attr(fn["attrs"], "pyfunction") and not fn["impl"]:
                pyfns[fn["name"]] = {"file": f["file"], "line": fn["line"], "attrs": fn["attrs"]}
        for t in f.get("types", []):
            if _attr(t["attrs"], "pyclass"):
                pyclasses[t["name"]] = (
                    _renamed(t["attrs"], t["name"]),
                    {"file": f["file"], "line": t["line"]},
                )

    def export_fn(rust, where):
        info = pyfns.get(rust, where)
        py = _renamed(info.get("attrs", []), rust)
        out[py] = {"rust": rust, "file": info["file"], "line": info["line"], "kind": "function"}

    def export_class(rust, where):
        py, info = pyclasses.get(rust, (rust, where))
        out[py] = {"rust": rust, "file": info["file"], "line": info["line"], "kind": "class"}

    # Module code = every #[pymodule] fn plus every fn it calls, transitively and across files
    # (panel B: `register_plasticity(m)?` registering exports in a helper).
    defined = {fn["name"] for f in file_facts for fn in f.get("fns", [])}
    modcode = {
        fn["name"] for f in file_facts for fn in f.get("fns", []) if _attr(fn["attrs"], "pymodule")
    }
    grew = True
    while grew:
        more = {
            c["path"].split("::")[-1]
            for f in file_facts
            for c in f.get("calls", [])
            if c["fn"] in modcode
        }
        more &= defined
        grew = not more <= modcode
        modcode |= more

    for f in file_facts:
        decl = {m["name"] for m in f.get("mods", []) if _attr(m["attrs"], "pymodule")}

        def in_decl(item, decl=decl):
            return item["mod"].split("::")[-1] in decl

        for u in f.get(
            "uses", []
        ):  # declarative: #[pymodule] mod m { #[pymodule_export] use super::f; }
            if _attr(u["attrs"], "pymodule_export") and in_decl(u):
                rust = u["path"].split("::")[-1]
                where = {"file": f["file"], "line": u["line"]}
                (export_class if rust in pyclasses else export_fn)(rust, where)
        for fn in f.get("fns", []):  # #[pyfunction] defined inside a declarative module
            if in_decl(fn) and _attr(fn["attrs"], "pyfunction"):
                export_fn(fn["name"], {"file": f["file"], "line": fn["line"]})
        for t in f.get("types", []):  # #[pyclass] defined inside a declarative module
            if in_decl(t) and _attr(t["attrs"], "pyclass"):
                export_class(t["name"], {"file": f["file"], "line": t["line"]})
        modfns = modcode
        # `let f = <init>;` or a plain `f = <rhs>;` in a module fn: (fn, local) -> [(end, start, scope,
        # init)]. The binding visible at a use is the latest one of that name that ENDED before it
        # (r3 F-2; r4 N-1: not visible in its own initializer) whose block scope is a prefix of the
        # use's (r5 R-1; Codex r6 reader 1: an assignment rebinds under the same rule). A wrapper init
        # binds, an identifier under `alias_root` layers aliases (RA-5/RA-6), anything else unbinds.
        bound: dict = {}
        rebinds = [
            *f.get("lets", []),
            *(
                {**a, "pat": a["lhs"], "init": a["rhs"]}
                for a in f.get("assigns", [])
                if a["op"] == "=" and _IDENT.fullmatch(a["lhs"].strip())
            ),
        ]
        for x in rebinds:
            if x["fn"] in modfns:
                key = (x["fn"], x["pat"].replace("mut ", "").strip())
                end = (x.get("end_line", x["line"]), x.get("end_col", x.get("col", 0)))
                start, scope = (x["line"], x.get("col", 0)), x.get("scope", [])
                bound.setdefault(key, []).append((end, start, scope, x["init"] or ""))

        def binding(fn, local, at, scope, bound=bound):
            prior = [
                b
                for b in sorted(bound.get((fn, local), []), key=lambda b: b[0])
                if b[0] <= at and b[2] == scope[: len(b[2])]
            ]
            if not prior:
                return None
            _, start, let_scope, init = prior[-1]
            m = _WRAP.search(init)
            if m:
                return m.group(1)
            alias = alias_root(init)
            return binding(fn, alias, start, let_scope) if alias else None

        for c in f.get("mcalls", []):
            if c["fn"] not in modfns:
                continue
            where = {"file": f["file"], "line": c["line"]}
            if c["name"] in (
                "add_function",
                "add_wrapped",
            ):  # only a wrapper that is ADDED registers (inline, or through a let-bound local)
                for a in c["args"]:
                    m = _WRAP.search(a)
                    at = (c["line"], c.get("col", 0))
                    name = m.group(1) if m else binding(c["fn"], a.strip(), at, c.get("scope", []))
                    if name:
                        export_fn(name.split("::")[-1], where)
            elif c["name"] == "add_class" and c.get("turbofish"):  # m.add_class::<T>()
                export_class(c["turbofish"].replace(" ", "").strip(":<>").split("::")[-1], where)
    registered = {v["rust"]: py for py, v in out.items() if v["kind"] == "class"}
    for f in file_facts:  # #[pymethods] impl T -> "PyName.member", for REGISTERED classes only
        for fn in f.get("fns", []):
            cls = (fn["impl"] or "").split("::")[-1]
            if fn["impl"] and _attr(fn["impl_attrs"], "pymethods") and cls in registered:
                member, kind = _method_key(fn)
                out[f"{registered[cls]}.{member}"] = {
                    "rust": f"{cls}::{fn['name']}",
                    "file": f["file"],
                    "line": fn["line"],
                    "kind": kind,
                }
    return out


# ---- Python references to the extension ------------------------------------------------------


def _module_of(py: Path, src: Path) -> str:
    rel = py.relative_to(src).with_suffix("")
    parts = list(rel.parts)
    if parts[-1] == "__init__":
        parts = parts[:-1]
    return ".".join(parts)


def _absolute(module: str | None, level: int, here: str, is_pkg: bool) -> str:
    if not level:
        return module or ""
    base = here.split(".") if is_pkg else here.split(".")[:-1]
    base = base[: len(base) - (level - 1)] if level > 1 else base
    return ".".join([*base, module] if module else base)


def python_native_refs(src: Path = ROOT / "src") -> dict[str, set[str]]:
    """{python module: names of `snn_data_lake._native` it uses}. "*" marks a star import."""
    refs: dict[str, set[str]] = {}
    pkg, _, leaf = NATIVE_MODULE.rpartition(".")
    for py in sorted(Path(src).rglob("*.py")):
        try:
            tree = ast.parse(py.read_text(encoding="utf-8"), filename=str(py))
        except (SyntaxError, UnicodeDecodeError):
            continue
        here = _module_of(py, Path(src))
        is_pkg = py.name == "__init__.py"
        aliases: set[str] = set()
        names: set[str] = set()
        pkg_aliases: set[str] = set()  # names bound to the package itself: `s` in `s._native.f`
        for n in ast.walk(tree):
            if isinstance(n, ast.ImportFrom):
                mod = _absolute(n.module, n.level, here, is_pkg)
                if mod == NATIVE_MODULE:
                    names |= {a.name for a in n.names}
                elif mod == pkg:
                    aliases |= {a.asname or a.name for a in n.names if a.name == leaf}
            elif isinstance(n, ast.Import):
                for a in n.names:
                    if a.name == NATIVE_MODULE and a.asname:
                        aliases.add(a.asname)
                    elif a.name == pkg or a.name.startswith(pkg + "."):
                        pkg_aliases.add(a.asname if a.asname and a.name == pkg else pkg)
        # `import snn_data_lake[.x] [as s]` then `s._native.f`: counted only where the module also
        # imports the extension somewhere (else `s._native` is someone else's import side effect).
        if (
            aliases
            or names
            or any(
                a.name == NATIVE_MODULE
                for n in ast.walk(tree)
                if isinstance(n, ast.Import)
                for a in n.names
            )
        ):
            aliases |= {f"{p}.{leaf}" for p in pkg_aliases}
        if aliases:
            for n in ast.walk(tree):
                if isinstance(n, ast.Attribute):
                    base = ast.unparse(n.value)
                    if base in aliases:
                        names.add(n.attr)
        if names or aliases:
            refs[here] = names or {"<module>"}
    return refs


