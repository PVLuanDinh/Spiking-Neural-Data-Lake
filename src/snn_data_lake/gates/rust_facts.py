"""
rust_facts -- the ONE Rust reader behind SNDL's Rust-aware gates (plan section 10, stage R0.2).

THE DEFECT THIS EXISTS FOR. Every policy gate here parses Python source and none knew Rust existed.
The owner ordered the C/C++-backed libraries replaced with Rust (2026-10-17), so code is about to move
into a crate under `native/` (`sndl-core`, pure Rust; `sndl-python`, the PyO3 bindings; built module
`snn_data_lake._native`). Moved code would leave P3, P6, P7 and the e-prop invariant unenforced.
Gate before rule: the gates learn to read Rust first, and this module is the reader they share, so no
gate re-derives the export map or re-parses a file (P2).

PARSER, CHOSEN ON MEASUREMENT (2026-10-17; the evidence is in the R0.2 row folder): `tools/rsfacts`, a
small syn-based binary that prints one JSON line of syntax facts per file. On five real crates (321
files, 162k lines) it parsed every file and agreed EXACTLY with tree-sitter-rust on 8,132 functions and
21,817 method calls, in about a second. tree-sitter-rust was rejected for four structural reasons, not
speed: it has no cp314t wheel and its build hard-codes the limited API, which the free-threaded build
refuses ("The limited API is not currently supported in the free-threaded build"); importing its core
binding RE-ENABLES THE GIL, the hazard CLAUDE.md's brian2 rule exists for; it returned error-recovered
partial trees for 4 of the 321 valid files without failing, which a gate cannot tolerate; and it is a
C library, against the directive this whole plan serves.

WHAT THIS MODULE DOES AND DOES NOT DO. It builds `tools/rsfacts` with cargo (its own target dir,
gitignored), runs it, and returns the facts. It derives the two joins five gates need:
  * `pyo3_exports(facts)` -- Python-visible name -> Rust item, for BOTH PyO3 module styles: the
    declarative `#[pymodule] mod m { #[pymodule_export] use super::f; }` (pyo3 0.30, what Phase 0
    built) and the function form `m.add_function(wrap_pyfunction!(f, m)?)` / `m.add_class::<T>()`,
    plus `#[pyo3(name = ...)]` / `#[pyclass(name = ...)]` renames and `#[pymethods]` methods;
  * `python_native_refs(src)` -- which Python modules reference which `_native` names, in every
    import spelling (`from snn_data_lake._native import f`, `from snn_data_lake import _native`,
    `import snn_data_lake._native as n` then `n.f`, and the relative forms).
Policy rules live in the gates, never here.

FAIL-CLOSED CONTRACT. No `.rs` under `native/` -> `native_status()` says ABSENT, printed so it is
never mistaken for "0 findings in N files". `.rs` present and cargo, the build or a parse fails ->
`RustFactsUnavailable`, which a gate must turn into a red, never a skip.

DISCLOSED BLIND SPOTS (print them beside any Rust verdict; `BLIND_SPOTS`):
  1. Macro bodies are token streams to syn: `vec![w.t()]`, `azip!(..)`, `s![..]` hold no calls,
     method calls or index expressions here. Their raw tokens are in `macros[*].tokens`.
  2. Name resolution is by LAST PATH SEGMENT within a crate; `crate::`/`super::`/`self::` and `use`
     aliases are resolved by the caller, approximately. Two items with one name are ambiguous.
  3. `#[cfg(...)]` items are all parsed regardless of features; `cfg(test)` is flagged per item.
  4. Code generated by `macro_rules!`, proc macros or `build.rs` is invisible.
"""

