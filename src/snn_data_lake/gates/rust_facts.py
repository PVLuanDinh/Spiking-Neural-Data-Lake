"""
rust_facts -- the ONE Rust reader behind SNDL's Rust-aware gates (plan section 10, stage R0.2).

THE DEFECT THIS EXISTS FOR. Every policy gate here parses Python source and none knew Rust existed.
The owner ordered the C/C++-backed libraries replaced with Rust (2026-10-17), so code is about to move
into a crate under `native/` (`sndl-core`, pure Rust; `sndl-python`, the PyO3 bindings; built module
`snn_data_lake._native`). Moved code would leave P3, P6, P7 and the e-prop invariant unenforced.
Gate before rule: the gates learn to read Rust first, and this module is the reader they share, so no
gate re-derives the export map or re-parses a file (P2).

PARSER, CHOSEN ON MEASUREMENT (2026-10-17; the evidence is in the R0.2 row folder): `tools/rsfacts`, a
small syn-based binary that prints one JSON line of syntax facts per file. On five real crates (321
files, 162k lines) it parsed every file and agreed EXACTLY with tree-sitter-rust on 8,132 functions and
21,817 method calls, in about a second. tree-sitter-rust was rejected for four structural reasons, not
speed: it has no cp314t wheel and its build hard-codes the limited API, which the free-threaded build
refuses ("The limited API is not currently supported in the free-threaded build"); importing its core
binding RE-ENABLES THE GIL, the hazard CLAUDE.md's brian2 rule exists for; it returned error-recovered
partial trees for 4 of the 321 valid files without failing, which a gate cannot tolerate; and it is a
C library, against the directive this whole plan serves.

WHAT THIS MODULE DOES AND DOES NOT DO. It builds `tools/rsfacts` with cargo (its own target dir,
gitignored), runs it, and returns the facts. It derives the two joins five gates need:
  * `pyo3_exports(facts)` -- Python-visible name -> Rust item, for BOTH PyO3 module styles: the
    declarative `#[pymodule] mod m { #[pymodule_export] use super::f; }` (pyo3 0.30, what Phase 0
    built) and the function form `m.add_function(wrap_pyfunction!(f, m)?)` / `m.add_class::<T>()`,
    plus `#[pyo3(name = ...)]` / `#[pyclass(name = ...)]` renames and `#[pymethods]` methods;
  * `python_native_refs(src)` -- which Python modules reference which `_native` names, in every
    import spelling (`from snn_data_lake._native import f`, `from snn_data_lake import _native`,
    `import snn_data_lake._native as n` then `n.f`, and the relative forms).
Policy rules live in the gates, never here.

FAIL-CLOSED CONTRACT. No `.rs` under `native/` -> `native_status()` says ABSENT, printed so it is
never mistaken for "0 findings in N files". `.rs` present and cargo, the build or a parse fails ->
`RustFactsUnavailable`, which a gate must turn into a red, never a skip.

DISCLOSED BLIND SPOTS (print them beside any Rust verdict; `BLIND_SPOTS`):
  1. Macro bodies are token streams to syn: `vec![w.t()]`, `azip!(..)`, `s![..]` hold no calls,
     method calls or index expressions here. Their raw tokens are in `macros[*].tokens`.
  2. Name resolution is by LAST PATH SEGMENT within a crate; `crate::`/`super::`/`self::` and `use`
     aliases are resolved by the caller, approximately. Two items with one name are ambiguous.
  3. `#[cfg(...)]` items are all parsed regardless of features; `cfg(test)` is flagged per item.
  4. Code generated by `macro_rules!`, proc macros or `build.rs` is invisible.
"""

from __future__ import annotations

import ast
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
NATIVE_DIR = "native"
RSFACTS = Path("tools") / "rsfacts"
NATIVE_MODULE = "snn_data_lake._native"
SCHEMA = 1

BLIND_SPOTS = (
    "macro bodies are opaque tokens (calls inside vec!/azip!/s! are not seen as calls)",
    "names resolve by last path segment within a crate (aliases/paths approximate)",
    "all #[cfg] items parsed regardless of features",
    "macro_rules!/proc-macro/build.rs generated code is invisible",
)


class RustFactsUnavailable(RuntimeError):
    """The Rust half of a gate could not run. A gate must report this as a RED, never skip it."""


def rust_files(root: Path = ROOT, sub: str = NATIVE_DIR) -> list[Path]:
    """Tracked and untracked-but-not-ignored `.rs` files under `sub` (git's view, like p4c_ratchet)."""
    base = Path(root)
    if not (base / sub).exists():
        return []
    try:
        out = subprocess.run(
            ["git", "-C", str(base), "ls-files", "-co", "--exclude-standard", "--", f"{sub}/*.rs"],
            capture_output=True,
            text=True,
            check=True,
        ).stdout
    except (OSError, subprocess.CalledProcessError) as exc:
        raise RustFactsUnavailable(f"git ls-files failed under {base / sub}: {exc}") from exc
    return sorted(base / p for p in out.splitlines() if p.strip())


def binary(root: Path = ROOT) -> Path:
    """Build (cargo no-ops when current) and return the rsfacts executable."""
    cargo = shutil.which("cargo")
    manifest = Path(root) / RSFACTS / "Cargo.toml"
    if cargo is None:
        raise RustFactsUnavailable("cargo not on PATH: the Rust half of this gate cannot run")
    if not manifest.exists():
        raise RustFactsUnavailable(f"missing {manifest}")
    target = Path(root) / RSFACTS / "target"
    env = dict(os.environ, CARGO_TARGET_DIR=str(target))
    r = subprocess.run(
        [cargo, "build", "--release", "--locked", "--quiet", "--manifest-path", str(manifest)],
        capture_output=True,
        text=True,
        env=env,
    )
    if r.returncode != 0:
        raise RustFactsUnavailable(f"rsfacts build failed:\n{r.stderr[-2000:]}")
    exe = target / "release" / ("rsfacts.exe" if os.name == "nt" else "rsfacts")
    if not exe.exists():
        raise RustFactsUnavailable(f"rsfacts built but {exe} is missing")
    return exe


def facts(paths, root: Path = ROOT, allow_errors: bool = False) -> list[dict]:
    """One fact dict per file. A parse failure raises unless `allow_errors` (self-checks only)."""
    paths = [str(p) for p in paths]
    if not paths:
        return []
    r = subprocess.run(
        [str(binary(root)), "-"], input="\n".join(paths), capture_output=True, text=True
    )
    if r.returncode != 0:
        raise RustFactsUnavailable(f"rsfacts exited {r.returncode}: {r.stderr[-2000:]}")
    out = [json.loads(line) for line in r.stdout.splitlines() if line.strip()]
    if len(out) != len(paths):
        raise RustFactsUnavailable(f"rsfacts returned {len(out)} records for {len(paths)} files")
    bad = [f for f in out if not f.get("ok") or f.get("schema") != SCHEMA]
    if bad and not allow_errors:
        raise RustFactsUnavailable(
            "unparseable Rust: " + "; ".join(f"{b['file']}: {b.get('err')}" for b in bad)
        )
    return out


def facts_for_source(
    text: str, name: str = "fixture.rs", root: Path = ROOT, allow_errors=False
) -> dict:
    """Facts for one snippet, via a temp file: the constructed-red helper every gate self-check uses."""
    with tempfile.TemporaryDirectory() as d:
        p = Path(d) / name
        p.write_text(text, encoding="utf-8")
        return facts([p], root, allow_errors=allow_errors)[0]


def native_status(root: Path = ROOT) -> tuple[str, list[dict]]:
    """("ABSENT", []) when there is no Rust under native/, else ("N files", facts). Fails closed."""
    files = rust_files(root)
    if not files:
        return "native/ ABSENT (0 .rs files)", []
    return f"native/ PRESENT ({len(files)} .rs files)", facts(files, root)


# ---- the PyO3 export map ---------------------------------------------------------------------

_NAME_ARG = re.compile(r'\bname\s*=\s*"([^"]+)"')


def _attr(attrs, head):
    """The first attribute whose path is `head` (exact), else None."""
    for a in attrs:
        if a == head or a.startswith(head + "("):
            return a
    return None


def _renamed(attrs, default):
    for a in attrs:
        if a.startswith(("pyo3(", "pyclass(", "pyfunction(")):
            m = _NAME_ARG.search(a)
            if m:
                return m.group(1)
    return default


def pyo3_exports(file_facts) -> dict[str, dict]:
    """Python-visible name -> {"rust": item name, "file", "line", "kind"}; class methods as "Cls.meth"."""
    out: dict[str, dict] = {}
    pyfns: dict[str, dict] = {}
    pyclasses: dict[str, tuple[str, dict]] = {}
    for f in file_facts:
        for fn in f.get("fns", []):
            if _attr(fn["attrs"], "pyfunction") and not fn["impl"]:
                pyfns[fn["name"]] = {"file": f["file"], "line": fn["line"], "attrs": fn["attrs"]}
        for t in f.get("types", []):
            if _attr(t["attrs"], "pyclass"):
                pyclasses[t["name"]] = (
                    _renamed(t["attrs"], t["name"]),
                    {"file": f["file"], "line": t["line"]},
                )

    def export_fn(rust, where):
        info = pyfns.get(rust, where)
        py = _renamed(info.get("attrs", []), rust)
        out[py] = {"rust": rust, "file": info["file"], "line": info["line"], "kind": "function"}

    def export_class(rust, where):
        py, info = pyclasses.get(rust, (rust, where))
        out[py] = {"rust": rust, "file": info["file"], "line": info["line"], "kind": "class"}

    for f in file_facts:
        decl = {m["name"] for m in f.get("mods", []) if _attr(m["attrs"], "pymodule")}
        for u in f.get(
            "uses", []
        ):  # declarative: #[pymodule] mod m { #[pymodule_export] use super::f; }
            if "pymodule_export" in u["attrs"] and u["mod"].split("::")[-1] in decl:
                rust = u["path"].split("::")[-1]
                where = {"file": f["file"], "line": u["line"]}
                (export_class if rust in pyclasses else export_fn)(rust, where)
        for fn in f.get("fns", []):  # #[pyfunction] defined inside a declarative module
            if fn["mod"].split("::")[-1] in decl and _attr(fn["attrs"], "pyfunction"):
                export_fn(fn["name"], {"file": f["file"], "line": fn["line"]})
        modfns = {fn["name"] for fn in f.get("fns", []) if _attr(fn["attrs"], "pymodule")}
        for m in f.get("macros", []):  # function form: m.add_function(wrap_pyfunction!(f, m)?)
            if m["name"].split("::")[-1] == "wrap_pyfunction" and m["fn"] in modfns:
                rust = m["tokens"].split(",")[0].strip().split("::")[-1].strip()
                export_fn(rust, {"file": f["file"], "line": m["line"]})
        for c in f.get("mcalls", []):  # m.add_class::<T>()
            if c["name"] == "add_class" and c["fn"] in modfns and c.get("turbofish"):
                rust = c["turbofish"].replace(" ", "").strip(":<>").split("::")[-1]
                export_class(rust, {"file": f["file"], "line": c["line"]})
    for f in file_facts:  # #[pymethods] impl T -> "PyName.method"
        for fn in f.get("fns", []):
            if fn["impl"] and _attr(fn["impl_attrs"], "pymethods"):
                cls = fn["impl"].split("::")[-1]
                pycls = pyclasses.get(cls, (cls, None))[0]
                py = _renamed(fn["attrs"], fn["name"])
                out[f"{pycls}.{py}"] = {
                    "rust": f"{cls}::{fn['name']}",
                    "file": f["file"],
                    "line": fn["line"],
                    "kind": "method",
                }
    return out


# ---- Python references to the extension ------------------------------------------------------


def _module_of(py: Path, src: Path) -> str:
    rel = py.relative_to(src).with_suffix("")
    parts = list(rel.parts)
    if parts[-1] == "__init__":
        parts = parts[:-1]
    return ".".join(parts)


def _absolute(module: str | None, level: int, here: str, is_pkg: bool) -> str:
    if not level:
        return module or ""
    base = here.split(".") if is_pkg else here.split(".")[:-1]
    base = base[: len(base) - (level - 1)] if level > 1 else base
    return ".".join([*base, module] if module else base)


def python_native_refs(src: Path = ROOT / "src") -> dict[str, set[str]]:
    """{python module: names of `snn_data_lake._native` it uses}. "*" marks a star import."""
    refs: dict[str, set[str]] = {}
    pkg, _, leaf = NATIVE_MODULE.rpartition(".")
    for py in sorted(Path(src).rglob("*.py")):
        try:
            tree = ast.parse(py.read_text(encoding="utf-8"), filename=str(py))
        except (SyntaxError, UnicodeDecodeError):
            continue
        here = _module_of(py, Path(src))
        is_pkg = py.name == "__init__.py"
        aliases: set[str] = set()
        names: set[str] = set()
        for n in ast.walk(tree):
            if isinstance(n, ast.ImportFrom):
                mod = _absolute(n.module, n.level, here, is_pkg)
                if mod == NATIVE_MODULE:
                    names |= {a.name for a in n.names}
                elif mod == pkg:
                    aliases |= {a.asname or a.name for a in n.names if a.name == leaf}
            elif isinstance(n, ast.Import):
                for a in n.names:
                    if a.name == NATIVE_MODULE:
                        aliases.add(a.asname or NATIVE_MODULE)
        if aliases:
            for n in ast.walk(tree):
                if isinstance(n, ast.Attribute):
                    base = ast.unparse(n.value)
                    if base in aliases:
                        names.add(n.attr)
        if names or aliases:
            refs[here] = names or {"<module>"}
    return refs


# ---- self-check ------------------------------------------------------------------------------

_FIXTURE = r"""
//! Doc comment mentioning w.t() and transpose() must NOT count as a call.
use ndarray::Array2;
use pyo3::prelude::*;

pub fn learn(w: &mut Array2<f64>, err: &Array2<f64>) {
    let s = "w.t() inside a string";
    let r = r#"transpose() inside a raw string"#;
    // w.t() in a line comment
    let fb = w.t().to_owned();
    *w -= &fb.dot(err);
    let v = vec![w.t()];
    let _ = (s, r, v);
}

#[pyclass(name = "Net")]
pub struct NetCore { w: Array2<f64> }

#[pymethods]
impl NetCore {
    fn step(&mut self) { self.w.swap_axes(0, 1); }
    #[pyo3(name = "learn_now")]
    fn learn_inner(&mut self) {}
}

#[pyfunction]
fn native_learn(x: f64) -> f64 { x * 2.0 }

#[pyfunction]
#[pyo3(name = "decay")]
fn decay_impl(x: f64) -> f64 { x * 0.5 }

#[pymodule(gil_used = false)]
mod _native {
    #[pymodule_export]
    use super::native_learn;
    #[pymodule_export]
    use super::NetCore;
}

#[pymodule]
fn _legacy(m: &Bound<'_, PyModule>) -> PyResult<()> {
    m.add_function(wrap_pyfunction!(decay_impl, m)?)?;
    m.add_class::<NetCore>()?;
    Ok(())
}

#[cfg(test)]
mod tests { #[test] fn t() {} }
"""

_PY_FIXTURE = {
    "snn_data_lake/__init__.py": "",
    "snn_data_lake/a.py": "from snn_data_lake._native import native_learn\n",
    "snn_data_lake/b.py": "from snn_data_lake import _native as nat\nx = nat.decay(1.0)\n",
    "snn_data_lake/sub/__init__.py": "",
    "snn_data_lake/sub/c.py": "from .. import _native\n_native.Net\n",
    "snn_data_lake/sub/d.py": "import snn_data_lake._native as n\nn.native_learn(2.0)\n",
    "snn_data_lake/e.py": "import json\njson.dumps({})\n",
}


def self_check(root: Path = ROOT) -> None:
    f = facts_for_source(_FIXTURE, root=root)
    fns = {fn["name"] for fn in f["fns"]}
    want = {"learn", "step", "learn_inner", "native_learn", "decay_impl", "_legacy", "t"}
    assert fns == want, f"fn census wrong: {sorted(fns ^ want)}"
    tcalls = [c for c in f["mcalls"] if c["name"] in {"t", "transpose", "swap_axes"}]
    assert [(c["name"], c["fn"]) for c in tcalls] == [("t", "learn"), ("swap_axes", "step")], tcalls
    assert any(m["name"] == "vec" and "w . t ()" in m["tokens"] for m in f["macros"]), (
        "macro tokens lost"
    )
    assert [fn["cfg_test"] for fn in f["fns"] if fn["name"] == "t"] == [True]
    ex = pyo3_exports([f])
    want_ex = {"native_learn", "Net", "decay", "Net.step", "Net.learn_now"}
    assert set(ex) == want_ex, f"export map wrong: {sorted(set(ex) ^ want_ex)}"
    assert (
        ex["decay"]["rust"] == "decay_impl"
        and ex["Net.learn_now"]["rust"] == "NetCore::learn_inner"
    )
    with tempfile.TemporaryDirectory() as d:
        for rel, text in _PY_FIXTURE.items():
            p = Path(d) / rel
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text, encoding="utf-8")
        refs = python_native_refs(Path(d))
    want_refs = {
        "snn_data_lake.a": {"native_learn"},
        "snn_data_lake.b": {"decay"},
        "snn_data_lake.sub.c": {"Net"},
        "snn_data_lake.sub.d": {"native_learn"},
    }
    assert refs == want_refs, f"python refs wrong: {refs}"
    # RED: a file rsfacts cannot parse must fail CLOSED, never be skipped.
    try:
        facts_for_source("fn broken( {", root=root)
    except RustFactsUnavailable:
        pass
    else:
        raise AssertionError("RED did not fire: unparseable Rust was accepted")
    bad = facts_for_source("fn broken( {", root=root, allow_errors=True)
    assert bad["ok"] is False and bad["err"], bad


def main() -> int:
    self_check()
    status, nf = native_status()
    tool = facts(rust_files(ROOT, str(RSFACTS)))
    print(
        f"rust_facts: self-check OK (fixture: 7 fns, 2 transpose calls, 5 exports, 4 _native importers; "
        f"unparseable-Rust RED fired) | {status} | tools/rsfacts: {len(tool)} file(s) parsed | "
        f"python _native importers in src: {len(python_native_refs())}"
    )
    print("rust_facts BLIND SPOTS: " + "; ".join(BLIND_SPOTS))
    return 0


if __name__ == "__main__":
    sys.exit(main())
