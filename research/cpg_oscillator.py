"""
Spiking central pattern generator (Matsuoka half-center oscillator) — rhythmic motor drive
(motor / robot-loop axis). Pure-stdlib.

The arm loop has reactive control (spiking_pid, reflex) but no RHYTHM generator — the neural circuit
that produces sustained oscillatory motion (a repetitive sweep / wave / gait) from a single tonic
command, the way a biological CPG drives locomotion without per-step planning. The Matsuoka
oscillator is the canonical model: two neurons that mutually inhibit, each with a slow adaptation
current, so the active one fatigues and hands off to the other -> a stable ANTI-PHASE rhythm. Two
motor knobs fall out: the adaptation time-constant sets the TEMPO (frequency) and a single tonic
"drive" scalar sets the VIGOR (amplitude) -- motor primitives for the arm. On-thesis (robot loop),
pairs with spiking_pid + arm_sim. Refs:
Matsuoka, "Sustained oscillations generated by mutually inhibiting neurons with adaptation", Biol.
Cybern. 52 (1985); Ijspeert, "Central pattern generators for locomotion", Neural Networks 21 (2008).

  Run: python cpg_oscillator.py        # (also run by run_selfchecks.py)
"""
import math


class MatsuokaCPG:
    """Two mutually-inhibiting adapting neurons -> a stable anti-phase oscillation."""

    def __init__(self, tau_r=0.1, tau_a=1.0, beta=2.5, w=2.5, dt=0.01):
        self.tau_r, self.tau_a, self.beta, self.w, self.dt = tau_r, tau_a, beta, w, dt
        self.reset()

    def reset(self):
        self.x1, self.v1, self.x2, self.v2 = 1.0, 0.0, 0.0, 0.0   # asymmetric start seeds the rhythm

    def step(self, drive):
        y1, y2 = max(0.0, self.x1), max(0.0, self.x2)
        dx1 = (-self.x1 - self.beta * self.v1 - self.w * y2 + drive) / self.tau_r
        dv1 = (-self.v1 + y1) / self.tau_a
        dx2 = (-self.x2 - self.beta * self.v2 - self.w * y1 + drive) / self.tau_r
        dv2 = (-self.v2 + y2) / self.tau_a
        self.x1 += self.dt * dx1
        self.v1 += self.dt * dv1
        self.x2 += self.dt * dx2
        self.v2 += self.dt * dv2
        return max(0.0, self.x1), max(0.0, self.x2)

    def run(self, drive, steps):
        self.reset()
        y1s, y2s = [], []
        for _ in range(steps):
            a, b = self.step(drive)
            y1s.append(a)
            y2s.append(b)
        return y1s, y2s


def _peaks(sig, thresh):
    """Count local maxima above a threshold (a cycle-count proxy for frequency)."""
    return sum(1 for t in range(1, len(sig) - 1)
               if sig[t] > thresh and sig[t] >= sig[t - 1] and sig[t] > sig[t + 1])


def _corr(a, b):
    n = len(a)
    ma, mb = sum(a) / n, sum(b) / n
    num = sum((x - ma) * (y - mb) for x, y in zip(a, b))
    da = math.sqrt(sum((x - ma) ** 2 for x in a))
    db = math.sqrt(sum((y - mb) ** 2 for y in b))
    return num / (da * db) if da and db else 0.0


def main():
    cpg = MatsuokaCPG()
    steps = 6000                                        # 60 s at dt=0.01

    y1, y2 = cpg.run(drive=1.0, steps=steps)
    amp = max(y1)
    thr = amp * 0.3
    n_peaks = _peaks(y1, thr)
    anti = _corr(y1, y2)

    # two independent motor knobs: adaptation time-constant sets TEMPO, tonic drive sets VIGOR
    fast_cycles = _peaks(MatsuokaCPG(tau_a=0.5).run(1.0, steps)[0], thr)   # shorter adaptation -> faster
    amp_hi = max(cpg.run(2.0, steps)[0])                                   # more drive -> bigger swing

    print("=" * 62)
    print("SPIKING CPG (Matsuoka half-center oscillator) — rhythmic motor drive")
    print("=" * 62)
    print(f"{steps} steps (dt={cpg.dt}); output amplitude {amp:.2f}, bounded")
    print(f"cycles (default tempo)   : {n_peaks}   anti-phase corr(y1,y2) = {anti:+.2f}")
    print(f"tempo knob tau_a 1.0->0.5: {n_peaks} -> {fast_cycles} cycles (faster rhythm)")
    print(f"vigor knob drive 1.0->2.0: amplitude {amp:.2f} -> {amp_hi:.2f}")
    print("=" * 62)

    # ---- self-check (ponytail: deterministic asserts, zero-dep) ----
    assert n_peaks >= 15, f"CPG must sustain a clear oscillation, not settle ({n_peaks} cycles)"
    assert anti < -0.3, f"the two half-centers must fire in ANTI-PHASE (corr {anti:+.2f})"
    assert amp < 1e3 and all(v == v for v in y1), "output must stay bounded (no blow-up / NaN)"
    assert fast_cycles > n_peaks, f"shorter adaptation must raise the tempo ({n_peaks} -> {fast_cycles})"
    assert amp_hi > amp, f"higher tonic drive must raise oscillation vigor ({amp:.2f} -> {amp_hi:.2f})"
    b = MatsuokaCPG().run(1.0, 500)[0]
    assert b == MatsuokaCPG().run(1.0, 500)[0], "same params -> identical trajectory (deterministic)"
    print(f"self-check OK: {n_peaks} cycles, anti-phase {anti:+.2f}; tempo {n_peaks}->{fast_cycles}, "
          f"vigor {amp:.2f}->{amp_hi:.2f}; deterministic")


if __name__ == "__main__":
    main()
